package com.jarbis.brokerage.service;

import com.jarbis.brokerage.dto.request.CreateOrderDisputeRequestDto;
import com.jarbis.brokerage.dto.response.OrderDisputeResponseDto;
import com.jarbis.brokerage.entity.Order;
import com.jarbis.brokerage.messaging.OrderAuditWriter;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;

@Service
@Transactional
public class OrderDisputeService {

	private final JdbcTemplate jdbcTemplate;
	private final OrderService orderService;
	 private final OrderAuditWriter audit;

	 public OrderDisputeService(JdbcTemplate jdbcTemplate, OrderService orderService, OrderAuditWriter audit) {
		this.jdbcTemplate = jdbcTemplate;
		this.orderService = orderService;
	  this.audit = audit;
	}

	public OrderDisputeResponseDto submit(Long orderId, CreateOrderDisputeRequestDto body) {
		if (body == null) {
			throw new IllegalArgumentException("Dispute request body is required");
		}
		String reason = normalize(body.getReason());
		String details = normalize(body.getDetails());
		if (reason.isBlank()) {
			throw new IllegalArgumentException("Dispute reason is required");
		}
		if (details.isBlank()) {
			throw new IllegalArgumentException("Dispute details are required");
		}
		if (details.length() > 2000) {
			throw new IllegalArgumentException("Dispute details cannot exceed 2000 characters");
		}

		ensureTable();
		Order order = orderService.getOrderById(orderId);
		Long accountId = order.getAccount().getId();

		Long id = jdbcTemplate.queryForObject(
				"""
				INSERT INTO public.order_disputes(order_id, account_id, reason, details, status)
				VALUES (?, ?, ?, ?, 'OPEN')
				RETURNING id
				""",
				Long.class,
				orderId,
				accountId,
				reason,
				details);
		audit.recordClientDispute(order, id, reason, details);

		return jdbcTemplate.queryForObject(
				"""
				SELECT id, order_id, account_id, reason, details, status, created_at, updated_at
				FROM public.order_disputes
				WHERE id = ?
				""",
				this::mapRow,
				id);
	}

	public List<OrderDisputeResponseDto> byOrder(Long orderId) {
		ensureTable();
		orderService.getOrderById(orderId);
		return jdbcTemplate.query(
				"""
				SELECT id, order_id, account_id, reason, details, status, created_at, updated_at
				FROM public.order_disputes
				WHERE order_id = ?
				ORDER BY created_at DESC, id DESC
				""",
				this::mapRow,
				orderId);
	}

	private String normalize(String value) {
		return value == null ? "" : value.trim();
	}

	private Instant toInstant(Timestamp value) {
		return value == null ? null : value.toInstant();
	}

	private OrderDisputeResponseDto mapRow(ResultSet rs, int rowNum) throws SQLException {
		OrderDisputeResponseDto dto = new OrderDisputeResponseDto();
		dto.setId(rs.getLong("id"));
		dto.setOrderId(rs.getLong("order_id"));
		dto.setAccountId(rs.getLong("account_id"));
		dto.setReason(rs.getString("reason"));
		dto.setDetails(rs.getString("details"));
		dto.setStatus(rs.getString("status"));
		dto.setCreatedAt(toInstant(rs.getTimestamp("created_at")));
		dto.setUpdatedAt(toInstant(rs.getTimestamp("updated_at")));
		return dto;
	}

	private void ensureTable() {
		jdbcTemplate.execute("""
				CREATE TABLE IF NOT EXISTS public.order_disputes (
				    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				    order_id BIGINT NOT NULL REFERENCES public.orders(id),
				    account_id BIGINT NOT NULL REFERENCES public.accounts(id),
				    reason VARCHAR(120) NOT NULL,
				    details VARCHAR(2000) NOT NULL,
				    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
				    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
				    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
				)
				""");
		jdbcTemplate.execute(
				"CREATE INDEX IF NOT EXISTS order_disputes_order_idx ON public.order_disputes(order_id, created_at DESC)");
	}

}