-- Application tables are explicitly in public; Flyway history lives in oltp_migrations.
-- IF NOT EXISTS preserves compatible local volumes previously created by Hibernate.
-- Hibernate validate rejects incompatible column types rather than altering/deleting data.
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_type VARCHAR(31) NOT NULL,
    name VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type VARCHAR(255) NOT NULL CHECK (account_type IN ('SAVINGS','CHECKING','INVESTMENT','CRYPTO')),
    currency VARCHAR(255) NOT NULL CHECK (currency IN ('USD','EUR','INR')),
    balance DOUBLE PRECISION NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES public.users(id)
);
CREATE TABLE IF NOT EXISTS public.holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES public.accounts(id),
    asset_id BIGINT NOT NULL REFERENCES public.assets(id),
    quantity DOUBLE PRECISION NOT NULL,
    average_price DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES public.assets(id),
    account_id BIGINT NOT NULL REFERENCES public.accounts(id),
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDING','PARTIALLY_FILLED','COMPLETED','CANCELLED')),
    side VARCHAR(255) NOT NULL CHECK (side IN ('BUY','SELL')),
    quantity DOUBLE PRECISION NOT NULL,
    remaining_quantity DOUBLE PRECISION NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    submitted_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES public.assets(id),
    quantity DOUBLE PRECISION NOT NULL,
    execution_price DOUBLE PRECISION NOT NULL,
    buy_order_id BIGINT NOT NULL REFERENCES public.orders(id),
    sell_order_id BIGINT NOT NULL REFERENCES public.orders(id),
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDING','COMPLETED','FAILED')),
    executed_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    replaced_by UUID,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE TABLE IF NOT EXISTS public.analytics_outbox (
    id UUID PRIMARY KEY,
    transaction_id BIGINT NOT NULL UNIQUE,
    payload TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS analytics_outbox_pending_idx ON public.analytics_outbox(published_at, created_at);
CREATE TABLE IF NOT EXISTS public.order_audit_outbox (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    order_id BIGINT NOT NULL,
    payload TEXT NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS order_audit_pending_idx ON public.order_audit_outbox(published_at, sequence);
CREATE TABLE IF NOT EXISTS public.market_data_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(255) NOT NULL,
    score_timestamp TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Matches the current JPA @Lob String mapping on PostgreSQL (large-object OID).
    payload OID NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_market_data_snapshots_symbol_timestamp
    ON public.market_data_snapshots(symbol, score_timestamp);
